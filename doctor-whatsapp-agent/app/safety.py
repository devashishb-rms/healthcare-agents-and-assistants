"""Deterministic safety gate. Runs BEFORE any LLM call and cannot be overridden by a prompt.

Tier 0 (EMERGENCY) patterns cover English, Hinglish (romanised Hindi) and Devanagari. The
list deliberately over-triggers: a false emergency costs one extra message; a miss can cost a life.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

# category -> list of regex patterns (case-insensitive)
EMERGENCY_PATTERNS: dict[str, list[str]] = {
    "self_harm": [
        r"\b(suicide|suicidal|kill myself|end my life|want to die|don'?t want to live|wanna die|hurt myself|self[- ]?harm)\b",
        r"\b(marna chahta|marna chahti|mar jaun|mar jaana chahta|jeena nahi chahta|jeena nahi chahti|khud ko (maar|nuksan)|zindagi khatam|sab khatam kar)\b",
        r"(आत्महत्या|मरना चाहत|जीना नहीं चाहत|खुद को (मार|नुकसान)|ज़िंदगी खत्म|जिंदगी खत्म)",
    ],
    "cardiac_respiratory": [
        r"\b(chest pain|chest tightness|pressure in (my )?chest|heart attack|can'?t breathe|cannot breathe|difficulty breathing|breathless|shortness of breath|turning blue|lips (are )?blue)\b",
        r"\b(seene (me|mein) dard|saans nahi aa|saans lene (me|mein) (takleef|dikkat|problem)|dil ka daura)\b",
        r"(सीने में दर्द|सांस नहीं आ|साँस नहीं आ|सांस लेने में|दिल का दौरा)",
    ],
    "neuro": [
        r"\b(unconscious|not responding|passed out|fainted and not waking|seizure|fits?\b|convulsion|face droop|slurred speech|stroke|sudden weakness|paralysis)\b",
        r"\b(behosh|daura (aa|pad)|daure|jhatke aa|mirgi|lakwa|bolne (me|mein) dikkat)\b",
        r"(बेहोश|दौरा|दौरे|झटके|मिर्गी|लकवा)",
    ],
    "bleeding_trauma": [
        r"\b(heavy bleeding|bleeding (a lot|heavily|won'?t stop)|blood (won'?t|not) stop|vomiting blood|coughing blood|severe injury|accident|road accident|fracture bone (sticking|out))\b",
        r"\b(bahut khoon|khoon (nahi|nhi) ruk|khoon ki ulti|accident ho gaya|bahut chot)\b",
        r"(बहुत खून|खून नहीं रुक|खून की उल्टी|एक्सीडेंट)",
    ],
    "allergy_poison": [
        r"\b(anaphyla|throat (is )?closing|swelling (of|in) (the )?(throat|tongue|face)|severe allergic|poison|overdose|took (too many|all the) (pills|tablets)|drank (phenyl|acid|kerosene))\b",
        r"\b(zeher|zehar|bahut saari goliyan|goliyan kha li|phenyl pi)\b",
        r"(ज़हर|जहर|गोलियां खा ली|गोलियाँ खा ली)",
    ],
    "pregnancy": [
        r"\b(pregnan\w*|pregnent|garbhvati|garbhawati).{0,60}\b(bleeding|blood|severe pain|no movement|baby (not|isn'?t) moving|water broke)\b",
        r"\b(bleeding|blood|severe pain|baby (not|isn'?t) moving).{0,60}\b(pregnan\w*|pregnent)\b",
        r"(गर्भ|प्रेग्नेंट).{0,40}(खून|ब्लीडिंग|दर्द)",
    ],
    "infant": [
        r"\b(\d{1,2}\s*(day|week)s? old|newborn|navjaat|new ?born).{0,60}\b(fever|bukhar|not feeding|limp|blue)\b",
        r"\b(fever|bukhar).{0,60}\b(\d{1,2}\s*(day|week)s? old|newborn)\b",
    ],
    "severe_pain_abdomen": [
        r"\b(severe|unbearable|worst) (abdominal|stomach|belly) pain\b",
        r"\b(pet (me|mein) (bahut|bohot) (tez|zyada) dard|asahya dard)\b",
    ],
    "explicit": [
        r"\b(emergency|urgent help|dying|serious condition|critical condition)\b",
        r"\b(emergency hai|bahut serious|jaan ka khatra|turant madad)\b",
        r"(इमरजेंसी|आपातकाल|जान का खतरा)",
    ],
}

_PRIORITY = ["self_harm", "pregnancy", "infant", "cardiac_respiratory", "neuro", "allergy_poison", "bleeding_trauma", "severe_pain_abdomen", "explicit"]
_COMPILED = {cat: [re.compile(p, re.IGNORECASE) for p in EMERGENCY_PATTERNS[cat]] for cat in _PRIORITY}

# Phrases that commonly produce false positives for "emergency"/"urgent" in admin contexts.
_ADMIN_URGENT_CONTEXT = re.compile(
    r"\b(urgent(ly)? (appointment|slot|booking)|emergency contact number|is this an emergency number|emergency ward timings?)\b",
    re.IGNORECASE,
)


@dataclass
class EmergencyHit:
    category: str
    matched: str


def detect_emergency(text: str) -> Optional[EmergencyHit]:
    """Return the first emergency category matched, or None."""
    if not text:
        return None
    t = text.strip()
    for cat, patterns in _COMPILED.items():
        for rx in patterns:
            m = rx.search(t)
            if m:
                if cat == "explicit" and _ADMIN_URGENT_CONTEXT.search(t):
                    continue
                return EmergencyHit(category=cat, matched=m.group(0))
    return None


def emergency_script(category: str, doctor_name: str, language: str = "en") -> str:
    """Scripted Tier-0 reply. Never generated by the LLM."""
    if language == "hi":
        base = (
            f"Yeh sun kar lagta hai ki turant madad ki zaroorat ho sakti hai. Kripya abhi 108 ya 112 par call karein, "
            f"ya nazdeeki emergency mein jayein. Main Dr. {doctor_name} ko turant soochit kar raha/rahi hoon. "
            "Agar ho sake to bataiye aap kahan hain aur aapke saath kaun hai."
        )
        if category == "self_harm":
            base += (
                "\n\nAap mahatvapurn hain, aur madad abhi uplabdh hai. Aap Tele-MANAS 14416 par call kar sakte hain "
                "(free, 24x7, kisi bhi bhasha mein). Main yahin hoon."
            )
        return base
    base = (
        f"This sounds like it may need urgent care. Please call 108 or 112 now, or go to the nearest emergency department. "
        f"I am alerting Dr. {doctor_name} immediately. If you can, tell me where you are and who is with you."
    )
    if category == "self_harm":
        base += (
            "\n\nYou matter, and help is available right now. You can call Tele-MANAS 14416 (free, 24x7, any language) "
            "while I alert the doctor. I'm here with you."
        )
    return base


_DEVANAGARI = re.compile(r"[ऀ-ॿ]")
_HINGLISH_HINTS = re.compile(
    r"\b(hai|hain|nahi|nhi|kya|mujhe|mera|meri|bukhar|dard|dawa|dawai|kab|aaj|kal|bachha|bachhe|doctor sahab|ji)\b",
    re.IGNORECASE,
)


def guess_language(text: str) -> str:
    """Very rough: 'hi' for Devanagari or Hinglish, else 'en'. The LLM does the real detection."""
    if _DEVANAGARI.search(text):
        return "hi"
    if len(_HINGLISH_HINTS.findall(text)) >= 2:
        return "hi"
    return "en"


# ---- Doctor control-number commands --------------------------------------------------------

_CMD = re.compile(r"^\s*(?:/)?(auto|draft|off|status|help)\s*$", re.IGNORECASE)
_DECISION = re.compile(r"^\s*([AEX])\s*(\d+)\s*(.*)$", re.IGNORECASE | re.DOTALL)


@dataclass
class DoctorCommand:
    kind: str                 # mode | approve | edit | discard | status | help
    value: Optional[str] = None
    draft_id: Optional[int] = None


def parse_doctor_command(text: str) -> Optional[DoctorCommand]:
    m = _CMD.match(text or "")
    if m:
        word = m.group(1).lower()
        if word in ("auto", "draft", "off"):
            return DoctorCommand(kind="mode", value=word)
        return DoctorCommand(kind=word)
    m = _DECISION.match(text or "")
    if m:
        letter, num, rest = m.group(1).upper(), int(m.group(2)), m.group(3).strip()
        if letter == "A":
            return DoctorCommand(kind="approve", draft_id=num)
        if letter == "X":
            return DoctorCommand(kind="discard", draft_id=num)
        if letter == "E" and rest:
            return DoctorCommand(kind="edit", draft_id=num, value=rest)
    return None
